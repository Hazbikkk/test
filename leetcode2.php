<?php

    function removeDuplicates(&$nums) {
        // Проверяем, пустой ли массив
        if (count($nums) == 0) {
            return 0;
        }

        // Указатель на позицию для следующего уникального элемента
        $k = 1;

        // Проходим по массиву, начиная с первого элемента
        for ($i = 1; $i < count($nums); $i++) {
            // Если текущий элемент отличается от последнего уникального
            if ($nums[$i] != $nums[$k - 1]) {
                // Записываем уникальный элемент на следующую позицию
                $nums[$k] = $nums[$i];
                $k++;
            }
            // Иначе пропускаем дубликат, ничего не делая
        }

        // Возвращаем количество уникальных элементов
        return $k;
    }

$nums = [1, 1, 2, 2];

echo removeDuplicates($nums);

?>